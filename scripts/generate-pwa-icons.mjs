async function squareIcon(size, innerPadding) {
  const inner = size - innerPadding * 2;
  const logoBuf = await sharp(logoPath)
    .resize(inner, inner, { fit: "inside" })
    .toBuffer();

  return sharp({
    create: {
      width: size,
      height: size,
      channels: 4,
      background: BG,
    },
  })
    .composite([{ input: logoBuf, gravity: "center" }])
    .png();
}

async function splashPng(width, height) {
  const logoMax = Math.round(Math.min(width, height) * 0.36);
  const logoBuf = await sharp(logoPath)
    .resize(logoMax, logoMax, { fit: "inside" })
    .toBuffer();

  return sharp({
    create: {
      width,
      height,
      channels: 4,
      background: BG,
    },
  })
    .composite([{ input: logoBuf, gravity: "center" }])
    .png();
}

async function main() {
  await mkdir(iconsDir, { recursive: true });

  await (await squareIcon(192, 16)).toFile(path.join(iconsDir, "icon-192.png"));
  await (await squareIcon(512, 48)).toFile(path.join(iconsDir, "icon-512.png"));
  await (await squareIcon(512, 88)).toFile(
    path.join(iconsDir, "icon-512-maskable.png"),
  );

  const appDir = path.join(root, "src", "app");
  await mkdir(appDir, { recursive: true });
  const icon192 = path.join(iconsDir, "icon-192.png");
  await copyFile(icon192, path.join(appDir, "icon.png"));
  await copyFile(icon192, path.join(appDir, "apple-icon.png"));

  await mkdir(splashDir, { recursive: true });
  for (const { w, h, media } of APPLE_SPLASHES) {
    const name = `apple-${w}x${h}.png`;
    await (await splashPng(w, h)).toFile(path.join(splashDir, name));
  }

  const genDir = path.join(root, "src", "lib", "generated");
  await mkdir(genDir, { recursive: true });
  const tsLines = APPLE_SPLASHES.map(({ w, h, media }) => {
    const file = `apple-${w}x${h}.png`;
    return `  { url: "/splash/${file}", media: ${JSON.stringify(media)} },`;
  }).join("\n");
  const tsPath = path.join(genDir, "pwa-apple-startup.ts");
  await writeFile(
    tsPath,
    `/** Generated by scripts/generate-pwa-icons.mjs — do not edit by hand. */\nexport const appleWebAppStartupImages = [\n${tsLines}\n] as const;\n`,
    "utf8",
  );

  console.log(
    "Wrote public/icons/*, public/splash/*, src/app/icon.png, src/app/apple-icon.png, src/lib/generated/pwa-apple-startup.ts",
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
